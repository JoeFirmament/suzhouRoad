#!/usr/bin/env python3
"""环秀山庄 · 主面构图线稿 v1（1008×688）。

依据：图 2-116 西南透视、2-115 西立面、1:5 模型（苏大建筑学院）、正文山高约 7m。
不是画：只定机位、体量、比例、洞口、桥/栏、植物落位。
"""
from PIL import Image, ImageDraw, ImageFont
from pathlib import Path

OUT = Path(__file__).resolve().parent
W, H = 1008, 688
F = lambda s: ImageFont.truetype('/System/Library/Fonts/Hiragino Sans GB.ttc', s)

def main():
    im = Image.new('RGB', (W, H), (246, 242, 231))
    d = ImageDraw.Draw(im, 'RGBA')

    # 高墙（右）
    d.rectangle([700,190,1008,650], fill=(225,220,208), outline=(90,88,80), width=2)
    d.rectangle([692,176,1008,196], fill=(80,82,78), outline=(60,60,56), width=1)
    for x in range(700,1008,26):
        d.line([(x,196),(x,214)], fill=(100,98,90), width=1)

    # 走马楼（已毁，1890 待核）：左后二层
    d.rectangle([0,230,120,650], fill=(225,220,208,150), outline=(90,88,80), width=2)
    d.polygon([(0,230),(60,208),(120,230),(120,248),(0,248)], fill=(70,72,66), outline=(50,50,46))
    d.line([(0,420),(120,420)], fill=(90,88,80), width=2)
    d.line([(0,432),(120,432)], fill=(90,88,80), width=1)
    # 廊 / 问泉亭（左前，低檐）
    d.polygon([(0,470),(60,442),(200,458),(200,488),(0,500)], fill=(70,72,66), outline=(50,50,46))
    d.rectangle([0,488,200,650], fill=(230,224,208,160), outline=(90,88,80), width=2)
    for x in (30,80,130,180):
        d.line([(x,488),(x,640)], fill=(90,88,80), width=3)
    d.line([(0,560),(200,560)], fill=(90,88,80), width=1)

    # 山体主轮廓（7m ≈ 519px，脚 650，顶 ≈ 131；取 170 留树冠）
    rock = [(170,650),(180,560),(160,500),(200,460),(210,400),(250,370),(270,320),
            (310,290),(330,240),(370,210),(390,170),(430,150),(460,180),(480,230),
            (520,250),(540,300),(580,320),(600,370),(640,400),(650,460),(690,490),
            (700,560),(730,600),(720,650)]
    d.polygon(rock, fill=(180,180,170,90), outline=(70,70,64), width=3)
    # 次峰（右）
    d.polygon([(720,650),(740,560),(780,520),(800,470),(840,500),(860,560),(880,620),(860,650)],
              fill=(170,170,160,90), outline=(70,70,64), width=3)
    # 洞
    d.polygon([(400,650),(400,560),(440,520),(490,560),(490,650)], fill=(40,42,38), outline=(30,30,28), width=2)
    d.polygon([(430,560),(440,540),(460,560),(460,600),(440,610),(430,590)], fill=(60,62,56))
    # 外挑石
    d.polygon([(360,320),(420,300),(470,330),(480,390),(440,420),(390,400),(360,360)],
              fill=(190,190,180,110), outline=(70,70,64), width=2)
    # 透孔
    for x,y,rx,ry in [(520,400,16,11),(600,480,13,9),(300,500,9,6),(560,560,10,7)]:
        d.ellipse([x-rx,y-ry,x+rx,y+ry], fill=(35,37,34))

    # 池 / 石栏 / 三曲桥
    d.rectangle([0,600,720,650], fill=(150,170,165,90), outline=(60,100,105), width=1)
    d.line([(0,612),(720,612)], fill=(70,72,66), width=4)
    for x in range(20,720,64):
        d.line([(x,612),(x,646)], fill=(70,72,66), width=3)
    d.line([(210,630),(250,612),(290,630),(330,612)], fill=(70,72,66), width=5)

    # 松（山体上）
    d.line([(560,340),(548,240),(536,180)], fill=(70,60,45), width=6)
    for cx,cy,rx,ry in [(530,170,52,34),(570,150,40,26),(500,190,34,22)]:
        d.ellipse([cx-rx,cy-ry,cx+rx,cy+ry], fill=(70,90,60,190), outline=(50,65,45))
    # 桂（廊前）
    d.ellipse([120,430,200,500], fill=(80,100,65,200), outline=(55,70,45))
    d.line([(160,500),(160,540)], fill=(70,60,45), width=5)
    # 竹（墙边）
    for x in (820,832,844,856):
        d.line([(x,650),(x+4,360)], fill=(70,100,60), width=3)
        for y in (420,470,520,570):
            d.line([(x+2,y),(x-14,y-10)], fill=(70,100,60), width=2)
    # 芭蕉（洞口）
    for a in (-60,-30,0,30,60):
        import math
        ang=math.radians(a)
        d.line([(470,600),(470+46*math.sin(ang),600-60*math.cos(ang))], fill=(80,110,65), width=4)

    im.save(OUT/'mainface-line-clean.png')

if __name__ == '__main__':
    main()
